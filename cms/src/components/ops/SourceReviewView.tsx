import { loadSourceReviewQueue } from './loadSourceReviewQueue'
import type { AdminViewServerProps } from 'payload'
import { DefaultTemplate } from '@payloadcms/next/templates'
import { Gutter } from '@payloadcms/ui'
import { redirect } from 'next/navigation'
import React from 'react'

import { SourceReviewQueue } from './SourceReviewQueue'

export async function SourceReviewView(props: AdminViewServerProps) {
  const { initPageResult, params, searchParams } = props
  const { req, visibleEntities, permissions, locale } = initPageResult

  if (!req.user) {
    redirect('/admin/login')
  }

  const { candidates, totals } = await loadSourceReviewQueue(req.payload, req.user)

  return (
    <DefaultTemplate
      i18n={req.i18n}
      locale={locale}
      params={params}
      payload={req.payload}
      permissions={permissions}
      searchParams={searchParams as Record<string, string | string[] | undefined>}
      user={req.user}
      visibleEntities={visibleEntities}
    >
      <Gutter>
        <SourceReviewQueue candidates={candidates} totals={totals} />
      </Gutter>
    </DefaultTemplate>
  )
}
